const assert = require('assert'); const os = require('os'); const fs = require('fs'); const path = require('path');
const { LocalStore } = require('../app/store');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'evst-'));
const s = new LocalStore(dir); let ev = 0; s.onChange(() => ev++);
s.set('tasks/t1', { title: 'a', meta: { x: 1, y: 2 }, n: 3 });
assert.equal(s.get('tasks/t1').version, 1);
s.update('tasks/t1', { meta: { y: 5, z: 6 }, n: { __delete__: true } });
assert.deepEqual(s.get('tasks/t1').data, { title: 'a', meta: { x: 1, y: 5, z: 6 } });
assert.throws(() => s.update('tasks/nope', { a: 1 }), e => e.code === 'not_found');
s.set('tasks/t2', { title: 'b', status: 'on_sheet', n: 2 }); s.set('tasks/t3', { title: 'c', status: 'queued', n: 1 });
assert.deepEqual(s.query('tasks', { where: [['status', 'in', ['on_sheet', 'queued']]], orderBy: [['n', 'asc']] }).map(r => r.id), ['t3', 't2']);
assert.deepEqual(s.query('tasks', { orderBy: [['title', 'desc']], limit: 1 }).map(r => r.id), ['t3']);
s.set('boards/b1/cols/c1', { a: 1 }); assert.equal(s.query('boards/b1/cols').length, 1);
assert.throws(() => s.get('tasks'), e => e.code === 'invalid_argument');
s.delete('tasks/t2'); assert.equal(s.get('tasks/t2').exists, false);
const s2 = new LocalStore(dir); assert.equal(s2.query('tasks').length, 2, 'persists to disk');
assert.ok(ev >= 6);
const snap = fs.mkdtempSync(path.join(os.tmpdir(), 'evsn-')); fs.mkdirSync(path.join(snap, 'brain'));
fs.writeFileSync(path.join(snap, 'brain', 'digest.json'), JSON.stringify({ id: 'digest', data: { headline: 'hi' }, version: 7, updatedAt: '2026-11-01T00:00:00Z' }));
const s3 = new LocalStore(fs.mkdtempSync(path.join(os.tmpdir(), 'evs3-'))); assert.equal(s3.importSnapshot(snap), 1);
assert.equal(s3.get('brain/digest').data.headline, 'hi'); assert.equal(s3.get('brain/digest').version, 7);
console.log('store ok');
const { readExport } = require('../app/importer');
const rows = readExport(JSON.stringify({ format: 'evolve-os-export', version: 1, collections: { brain: { digest: { headline: 'x' } }, prospects: { a: { name: 'A' }, b: { name: 'B' } } } }));
assert.equal(rows.length, 3); assert.deepEqual(rows[0], { col: 'brain', id: 'digest', data: { headline: 'x' }, version: 1 });
assert.throws(() => readExport('{"projects":{}}'));
console.log('importer ok');
